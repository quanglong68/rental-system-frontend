/** Spring Data Page (serialization mặc định: content/number/size/totalElements/totalPages). */
export type PageResponse<T> = {
  content: T[];
  number: number;
  size: number;
  totalElements: number;
  totalPages: number;
};

/** Chấp nhận PageResponse chuẩn (page phẳng dạng số) và Spring Page (number / page lồng). */
type RawPage<T> = Partial<PageResponse<T>> & {
  page?: number | { number?: number; size?: number; totalElements?: number; totalPages?: number };
  content?: T[];
  totalPages?: number;
};

function toPage<T>(raw: RawPage<T>): PageResponse<T> {
  const dto = typeof raw.page === "object" ? raw.page : undefined;
  const flatPage = typeof raw.page === "number" ? raw.page : undefined;
  return {
    content: raw.content ?? [],
    number: raw.number ?? flatPage ?? dto?.number ?? 0,
    size: raw.size ?? dto?.size ?? 0,
    totalElements: raw.totalElements ?? dto?.totalElements ?? 0,
    totalPages: raw.totalPages ?? dto?.totalPages ?? 0,
  };
}

type Query = Record<string, string | number | boolean | undefined>;

function qs(params: Query): string {
  const search = new URLSearchParams();
  for (const [key, value] of Object.entries(params)) {
    if (value !== undefined && value !== "") search.set(key, String(value));
  }
  const q = search.toString();
  return q ? `?${q}` : "";
}

